"""Move results to ITW/dt2_results/<KEY>, combined ROC (roc_plot.sh style), summary, one zip per dataset.

All outputs end up in the top-level ITW folder: dt2_results/ and <KEY>_dt2_results.zip.
Zips hold only the results generated by this evaluation, never dataset images.

Usage: python finalize.py AWE ITW UBEAR NITJ
"""
import os
import re
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

from datasets import DATASETS, PROJECT_DIR

BASH = r'C:\Program Files\Git\bin\bash.exe'
RESULTS_ROOT = PROJECT_DIR / 'dt2_results'


def output_dir(key):
    return RESULTS_ROOT / key


def relocate(key):
    # Move <dataset>/dt2_results -> ITW/dt2_results/<KEY>, keeping gallery image links valid.
    old = DATASETS[key][1] / 'dt2_results'
    new = output_dir(key)
    if not old.exists():
        return
    RESULTS_ROOT.mkdir(exist_ok=True)
    html_dir = old / 'run' / key / 'html'
    old_rel = Path(os.path.relpath(DATASETS[key][1], html_dir)).as_posix()
    new_rel = Path(os.path.relpath(DATASETS[key][1], new / 'run' / key / 'html')).as_posix()
    shutil.move(str(old), str(new))
    if old_rel != new_rel:
        for page in (new / 'run' / key / 'html').glob('*.html'):
            text = page.read_text(encoding='utf-8')
            page.write_text(text.replace(f'src="{old_rel}/', f'src="{new_rel}/'), encoding='utf-8')


def parse_sts(path):
    text = path.read_text()
    eer = re.search(r'\(EER\) = \s*\(([-\d.]+)\)\s+([-\d.]+)', text)
    pick = lambda pat: re.search(pat, text).group(1)
    return {
        'DI': float(pick(r'\(DI\) = ([-\d.e]+)')),
        'CRR': float(pick(r'\(CRR\) =\s+([-\d.e]+)')),
        'EER': float(eer.group(1)),
        'EER_threshold': float(eer.group(2)),
        'FAR': float(pick(r'\(FAR\) = \s*([-\d.e]+)')),
        'FRR': float(re.findall(r'\(FAR\) = \s*([-\d.e]+)', text)[1]),
        'FR': pick(r'Falsely Reject Matching =\s+(\d+ out of total \d+)'),
        'FA': pick(r'Falsely Accept Matching =\s+(\d+ out of total \d+)'),
        'failed': pick(r'Total Failed Subject =\s+(\d+ \(out of \d+\))'),
    }


def parse_kv(path):
    out = {}
    for line in path.read_text().splitlines():
        if ': ' in line:
            k, v = line.split(': ', 1)
            out[k.strip()] = v.strip()
    return out


def combined_roc(keys):
    target = RESULTS_ROOT / 'combined'
    target.mkdir(exist_ok=True)
    curves = ',\\\n'.join(
        f'"{(output_dir(k) / "run" / k / f"{k}_FAR_FRR_Data.dat").as_posix()}" using 6:3 title \'{k}\' w lines lw 2'
        for k in keys)
    script = f'''gnuplot << PLOTTHIS
set terminal png enhanced font 'Verdana,12' size 900,700
set output "{(target / 'ROC_all_datasets.png').as_posix()}"
set grid
set title "ROC based Comparative Analysis"
set key right top
set logscale x
set yrange [0:100]
set xrange [0.01:100]
set xlabel "FAR (%) (Plotted in Log-Scale)"
set ylabel "FRR (%)"
plot {curves}
PLOTTHIS'''
    env = dict(os.environ)
    env['PATH'] = os.pathsep.join([r'C:\Program Files\gnuplot\bin', env['PATH']])
    subprocess.run([BASH, '-c', script], env=env, check=True)
    return target


def make_zip(key):
    out = output_dir(key)
    zip_path = PROJECT_DIR / f'{key}_dt2_results.zip'
    with zipfile.ZipFile(zip_path, 'w', zipfile.ZIP_DEFLATED, allowZip64=True, compresslevel=6) as z:
        for folder in (out, RESULTS_ROOT / 'combined'):
            for root, _, files in os.walk(folder):
                for name in files:
                    full = os.path.join(root, name)
                    z.write(full, os.path.relpath(full, RESULTS_ROOT))
    return zip_path


def main(keys):
    for k in keys:
        relocate(k)
    target = combined_roc(keys)
    rows = []
    for k in keys:
        out = output_dir(k)
        rows.append((k, parse_kv(out / 'run_info.txt'), parse_sts(out / 'run' / k / f'{k}.sts'),
                     parse_kv(out / 'cross_check.txt')))
    lines = ['Ear matching evaluation - scripts_d_t_2 (main.sh via max_min.sh)',
             'Model: best_pruned_35per_tinyvit.pt (7.526 M params); embed -> L2 -> minus global mean -> L2',
             'Score: 1 - cosine, min-max normalized by max_min.sh; all ordered pairs i != j', '',
             f'{"Dataset":<8}{"Images":>8}{"Subj":>6}{"Genuine":>12}{"Impostor":>14}'
             f'{"EER%":>9}{"CRR%":>8}{"DI":>9}{"FAR%":>9}{"FRR%":>9}{"VER@0.1%":>10}{"VER@1%":>9}{"AUC":>9}']
    for k, info, sts, chk in rows:
        lines.append(f'{k:<8}{info["images"]:>8}{info["subjects"]:>6}{info["genuine pairs"]:>12}'
                     f'{info["impostor pairs"]:>14}{sts["EER"]:>9.3f}{sts["CRR"]:>8.2f}{sts["DI"]:>9.3f}'
                     f'{sts["FAR"]:>9.3f}{sts["FRR"]:>9.3f}{float(chk["VER@FAR=0.1% (%)"]):>10.2f}'
                     f'{float(chk["VER@FAR=1% (%)"]):>9.2f}{float(chk["AUC"]):>9.4f}')
    lines += ['', 'EER/CRR/DI/FAR/FRR from the scripts (.sts); VER and AUC from cross_check.txt (sklearn).',
              'DI is negative because scores are dissimilarities (genuine mean < impostor mean).', '']
    for k, info, sts, chk in rows:
        lines.append(f'{k}: EER threshold {sts["EER_threshold"]}; FR {sts["FR"]}; FA {sts["FA"]}; '
                     f'CRR failures {sts["failed"]}; cross-check EER {float(chk["EER (%)"]):.3f}%, '
                     f'Rank-1 {float(chk["Rank-1 (%)"]):.2f}%')
    (target / 'summary.txt').write_text('\n'.join(lines) + '\n')
    print('\n'.join(lines))
    for k in keys:
        print('zipped', make_zip(k), flush=True)


if __name__ == '__main__':
    main(sys.argv[1:])
